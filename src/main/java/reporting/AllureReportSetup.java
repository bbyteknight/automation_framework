package reporting;

import config.ConfigReader;
import exceptions.FrameworkException;

import java.io.IOException;
import java.io.InputStream;
import java.io.OutputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.util.Properties;

/**
 * Prepares target/allure-results before any scenario runs, for the two things Allure never
 * infers on its own:
 *  - environment.properties: populates the report's "Environment" widget with what this run
 *    actually used (env/platform/browser/device/execution mode/build) — Allure just displays
 *    whatever key=value pairs are in this file.
 *  - categories.json: classifies failures (product defect vs. config/test-data/infra problem)
 *    by matching the custom exception types in exceptions/ against the failure stack trace.
 */
public final class AllureReportSetup {

    private static final Path RESULTS_DIR = Path.of("target", "allure-results");
    private static final String CATEGORIES_CLASSPATH_RESOURCE = "allure/categories.json";

    private AllureReportSetup() {
    }

    public static void prepare() {
        writeEnvironment();
        copyCategories();
    }

    private static void writeEnvironment() {
        Properties props = new Properties();
        props.setProperty("Environment", ConfigReader.get("env"));
        props.setProperty("Platform", ConfigReader.get("platform"));
        props.setProperty("Browser", "web".equalsIgnoreCase(ConfigReader.get("platform"))
                ? ConfigReader.get("browser") : "N/A");
        props.setProperty("Device", describeDevice());
        props.setProperty("ExecutionMode", ConfigReader.get("executionMode"));
        props.setProperty("Build", ConfigReader.get("buildNumber", "local"));

        try {
            Files.createDirectories(RESULTS_DIR);
            try (OutputStream out = Files.newOutputStream(RESULTS_DIR.resolve("environment.properties"))) {
                props.store(out, "Generated by AllureReportSetup at test run time");
            }
        } catch (IOException e) {
            throw new FrameworkException("❗ Could not write Allure environment.properties", e);
        }
    }

    private static String describeDevice() {
        String deviceName = ConfigReader.get("deviceName", "");
        if (!deviceName.isBlank()) {
            return deviceName;
        }
        String avd = ConfigReader.get("avd", "");
        if (!avd.isBlank()) {
            return avd;
        }
        return "N/A";
    }

    private static void copyCategories() {
        try (InputStream categories = AllureReportSetup.class.getClassLoader()
                .getResourceAsStream(CATEGORIES_CLASSPATH_RESOURCE)) {
            if (categories == null) {
                throw new FrameworkException(
                        "❗ Allure categories.json not found on classpath: " + CATEGORIES_CLASSPATH_RESOURCE);
            }
            Files.createDirectories(RESULTS_DIR);
            Files.copy(categories, RESULTS_DIR.resolve("categories.json"), StandardCopyOption.REPLACE_EXISTING);
        } catch (IOException e) {
            throw new FrameworkException("❗ Could not write Allure categories.json", e);
        }
    }
}
