package steps;

import com.fasterxml.jackson.databind.ObjectMapper;
import context.ScenarioContext;
import exceptions.FrameworkException;
import io.cucumber.datatable.DataTable;
import io.cucumber.java.en.And;
import io.cucumber.java.en.Then;
import org.testng.Assert;
import utils.CsvUtil;
import utils.ExcelUtil;

import java.util.List;
import java.util.Map;
import java.util.UUID;

/**
 * Generic steps for validating an exported CSV/Excel report's content — header row, row count,
 * individual cells, and comparison against the API data it was exported from — backed by
 * {@code utils.CsvUtil}/{@code utils.ExcelUtil}. The report is generated by the {@code And} steps
 * here from whatever's stashed in {@code ScenarioContext} under {@code createdObject} (the same
 * convention {@code steps.ObjectSteps}/{@code steps.DbSteps} already use), since no real
 * report-export feature exists in this framework yet; point the same {@code Then} steps at a real
 * exported file's path once one does.
 */
public class ReportSteps {

    private static final String REPORT_PATH_KEY = "currentReportPath";
    private static final String REPORT_FORMAT_KEY = "currentReportFormat";
    private static final String SHEET_NAME = "Objects";
    private static final List<String> COLUMNS = List.of("id", "name", "price");

    private static final ObjectMapper OBJECT_MAPPER = new ObjectMapper();

    private final ScenarioContext scenarioContext;

    public ReportSteps(ScenarioContext scenarioContext) {
        this.scenarioContext = scenarioContext;
    }

    @And("the created object is exported to a CSV report")
    public void theCreatedObjectIsExportedToACsvReport() {
        String path = "target/report-fixtures/objects-" + UUID.randomUUID() + ".csv";
        CsvUtil.createCsv(path, COLUMNS, List.of(exportedObjectRow()));
        scenarioContext.set(REPORT_PATH_KEY, path);
        scenarioContext.set(REPORT_FORMAT_KEY, "csv");
    }

    @And("the created object is exported to an Excel report")
    public void theCreatedObjectIsExportedToAnExcelReport() {
        String path = "target/report-fixtures/objects-" + UUID.randomUUID() + ".xlsx";
        ExcelUtil.createExcel(path, SHEET_NAME, COLUMNS, List.of(exportedObjectRow()));
        scenarioContext.set(REPORT_PATH_KEY, path);
        scenarioContext.set(REPORT_FORMAT_KEY, "excel");
    }

    @Then("the exported report header row should be:")
    public void theExportedReportHeaderRowShouldBe(DataTable dataTable) {
        // A single-row, multi-column table — asList(String.class) only has a built-in converter
        // for single-COLUMN tables, so read the one row's cells directly instead.
        List<String> expected = dataTable.cells().get(0);
        List<String> actual = isCsv() ? CsvUtil.headers(currentPath()) : ExcelUtil.headers(currentPath(), SHEET_NAME);
        Assert.assertEquals(actual, expected);
    }

    @Then("the exported report should contain {int} data row(s)")
    public void theExportedReportShouldContainDataRows(int expectedCount) {
        int actual = isCsv() ? CsvUtil.rowCount(currentPath()) : ExcelUtil.rowCount(currentPath(), SHEET_NAME);
        Assert.assertEquals(actual, expectedCount);
    }

    @Then("the {string} column of row {int} in the exported report should be {string}")
    public void theColumnOfRowInTheExportedReportShouldBe(String column, int rowIndex, String expectedValue) {
        Assert.assertEquals(readCell(rowIndex, column), expectedValue);
    }

    @Then("the {string} column of the exported report should equal the {string} field of {string}")
    public void theColumnOfTheExportedReportShouldEqualTheFieldOf(String reportColumn, String apiField, String contextKey) {
        Map<String, Object> apiObject = toMap(scenarioContext.get(contextKey));
        String actual = readCell(0, reportColumn);
        Assert.assertEquals(actual, String.valueOf(apiObject.get(apiField)),
                reportColumn + " in the exported report did not match \"" + apiField + "\" from " + contextKey);
    }

    private List<String> exportedObjectRow() {
        Map<String, Object> apiObject = toMap(scenarioContext.get("createdObject"));
        @SuppressWarnings("unchecked")
        Map<String, Object> data = (Map<String, Object>) apiObject.get("data");
        return List.of(
                String.valueOf(apiObject.get("id")),
                String.valueOf(apiObject.get("name")),
                String.valueOf(data.get("price")));
    }

    private String readCell(int rowIndex, String column) {
        return isCsv() ? CsvUtil.readCell(currentPath(), rowIndex, column)
                : ExcelUtil.readCell(currentPath(), SHEET_NAME, rowIndex, column);
    }

    private boolean isCsv() {
        return "csv".equals(scenarioContext.get(REPORT_FORMAT_KEY, String.class));
    }

    private String currentPath() {
        return scenarioContext.get(REPORT_PATH_KEY, String.class);
    }

    @SuppressWarnings("unchecked")
    private Map<String, Object> toMap(Object apiObject) {
        if (apiObject == null) {
            throw new FrameworkException("❗ No value found in the scenario context to compare against the exported report");
        }
        return OBJECT_MAPPER.convertValue(apiObject, Map.class);
    }
}
